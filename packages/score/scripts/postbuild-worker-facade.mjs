import { existsSync } from "node:fs";
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Relative worker spawns (`new URL('./worker.js', import.meta.url)`) resolve
 * against wherever esbuild placed the surrounding code. Entry modules that
 * are also imported by other entries get demoted to re-export facades with
 * their real code hoisted into dist-root chunks, so a spawn can execute with
 * `import.meta.url` at dist/ itself.
 *
 * This script (1) writes a dist/worker.js facade that re-hosts the analyze
 * module worker for spawn sites hoisted to the root, and (2) asserts that
 * every spawn site in the ESM dist has a worker.js next to it, and that the
 * io spawn stayed inside its own entry (the root facade can only ever mean
 * the analyze worker — if the io spawn floats into a root chunk one day,
 * this check must fail rather than silently serve it the wrong worker).
 */
const dist = fileURLToPath(new URL("../dist", import.meta.url));
const SPAWN = 'new URL("./worker.js", import.meta.url)';

await writeFile(
  path.join(dist, "worker.js"),
  [
    "// Generated by scripts/postbuild-worker-facade.mjs — do not edit.",
    "// Re-hosts the analyze module worker for spawn sites hoisted into",
    "// dist-root chunks, where `./worker.js` resolves against dist/ itself.",
    'import "./analyze/worker.js";',
    "",
  ].join("\n"),
);

const spawnSites = [];
for (const file of await readdir(dist, { recursive: true })) {
  if (!file.endsWith(".js") || file.endsWith(".global.js")) continue;
  const filePath = path.join(dist, file);
  if ((await readFile(filePath, "utf8")).includes(SPAWN)) {
    spawnSites.push(file);
  }
}

const errors = [];
for (const file of spawnSites) {
  const sibling = path.join(dist, path.dirname(file), "worker.js");
  if (!existsSync(sibling)) {
    errors.push(`${file}: spawn site has no sibling worker.js (${sibling}).`);
  }
}
if (!spawnSites.includes(path.join("io", "worker-client.js"))) {
  errors.push(
    "io/worker-client.js no longer contains its worker spawn — it was hoisted " +
      "into a shared chunk, where ./worker.js would resolve to the analyze " +
      "facade. Restructure so the io spawn stays in its entry.",
  );
}

if (errors.length > 0) {
  console.error(`Worker URL layout check failed with ${errors.length} problem(s):`);
  for (const error of errors) console.error(`- ${error}`);
  process.exit(1);
}
console.log(`Worker URL layout verified for ${spawnSites.length} spawn sites.`);
