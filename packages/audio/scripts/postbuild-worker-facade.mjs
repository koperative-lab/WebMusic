import { existsSync } from "node:fs";
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Relative worker spawns resolve against wherever esbuild placed the
 * surrounding code — an entry file, or a shared chunk at the dist root. Each
 * family worker spawns via a UNIQUE static filename (`decoder-worker.js` for
 * play, `analysis-worker.js` for analyze), and this script re-hosts the right
 * worker next to every emitted spawn site, so the relative URL is correct in
 * every placement and consumer bundlers see a statically analyzable asset.
 * It fails the build if a spawn site cannot be paired with its worker.
 */
const dist = fileURLToPath(new URL("../dist", import.meta.url));

const FACADES = [
  {
    filename: "decoder-worker.js",
    spawn: 'new URL("./decoder-worker.js", import.meta.url)',
    worker: path.join("play", "worker.js"),
  },
  {
    filename: "analysis-worker.js",
    spawn: 'new URL("./analysis-worker.js", import.meta.url)',
    worker: path.join("analyze", "worker.js"),
  },
];

const files = (await readdir(dist, { recursive: true }))
  .filter((file) => file.endsWith(".js") && !file.endsWith(".global.js"));

let sites = 0;
const errors = [];
for (const facade of FACADES) {
  if (!existsSync(path.join(dist, facade.worker))) {
    errors.push(`missing worker runtime dist/${facade.worker}.`);
    continue;
  }
  let facadeSites = 0;
  for (const file of files) {
    const content = await readFile(path.join(dist, file), "utf8");
    if (!content.includes(facade.spawn)) continue;
    sites += 1;
    facadeSites += 1;
    const siteDir = path.dirname(path.join(dist, file));
    const target = path
      .relative(siteDir, path.join(dist, facade.worker))
      .replaceAll(path.sep, "/");
    await writeFile(
      path.join(siteDir, facade.filename),
      [
        "// Generated by scripts/postbuild-worker-facade.mjs — do not edit.",
        `// Re-hosts the ${facade.worker.replaceAll(path.sep, "/")} module worker next to a spawn site.`,
        `import "${target.startsWith(".") ? target : `./${target}`}";`,
        "",
      ].join("\n"),
    );
  }
  // Per-facade, not a global total: if esbuild ever rewrites ONE worker's
  // spawn literal while the other survives, a global count would pass and
  // that capability's default worker would 404 in bundled apps — the exact
  // historical failure this script exists to prevent.
  if (facadeSites === 0) {
    errors.push(`no spawn sites found for ${facade.filename} — the static spawn literal for dist/${facade.worker} disappeared.`);
  }
}
if (errors.length > 0) {
  console.error(`Worker facade generation failed with ${errors.length} problem(s):`);
  for (const error of errors) console.error(`- ${error}`);
  process.exit(1);
}
console.log(`Worker facades generated for ${sites} spawn sites.`);
