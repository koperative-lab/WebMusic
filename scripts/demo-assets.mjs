export const title = 'WebMusic Study No. 1';
export const author = 'WebMusic Contributors';
export const sampleRate = 44100;
export const durationSeconds = 32;
const basename = 'webmusic-study-no-1';
const inventoryPath = 'licenses/DEMO_ASSETS.json';
const licensePath = 'licenses/DEMO_ASSETS_MIT.txt';
// MP3 cannot be regenerated by ordinary CI without the external encoder.
// Pin its reviewed bytes separately from refreshable inventories.
const encodedAudioHash = '2a8d6eb85eefec8d385edf365004c45b7a6800c693e16f9209d1dea194658196';
// The exact WAV the reviewed MP3 was encoded from. Replace both pins together
// after reviewing a newly encoded MP3 against changed synthesis or license text.
const encodedSourceHash = '445b82324fd49ce39d0a0e4a5304c1d4467d753f97587f8f3bdc22204fd7210f';
const iconHash = '3d81ddf500aae3a6f7638d7ee65ad36dc81155336970fd57e8ed407138cc68d0';
const chords = [[60, 64, 67], [57, 60, 64], [53, 57, 60], [55, 59, 62]];
const figures = [[0, 1, 2, 1, 0, 2, 1, 2, 0, 2, 1, 0], [2, 0, 1, 2, 1, 0, 1, 0, 2, 0, 2, 1]];

export function originalNotes() {
  return Array.from({length: 16}, (_, bar) => [1, 2].flatMap((staff) =>
    Array.from({length: 12}, (_, index) => {
      const chord = chords[bar % chords.length];
      const degree = figures[Math.floor(bar / 4) % 2][staff === 1 ? index : (index + 3) % 12];
      return {
        bar: bar + 1, staff, index,
        midi: chord[degree] + (staff === 1 ? 12 : 0),
        rest: staff === 1 && index === 11 && [3, 7, 11].includes(bar),
      };
    }))).flat();
}

function pitchXML(midi) {
  const step = ['C', '', 'D', '', 'E', 'F', '', 'G', '', 'A', '', 'B'][midi % 12];
  if (!step) throw new Error('The original study uses only natural pitches.');
  return `<pitch><step>${step}</step><octave>${Math.floor(midi / 12) - 1}</octave></pitch>`;
}

function noteXML(note) {
  const {bar, staff, index, midi, rest} = note;
  const hiddenNumber = Math.floor(index / 3) % 2 === 1;
  const marks = [];
  if (index % 3 === 0) marks.push(`<tuplet type="start" number="1" bracket="no" show-number="${hiddenNumber ? 'none' : 'actual'}"/>`);
  if (index % 3 === 2) marks.push(`<tuplet type="stop" number="1" show-number="${hiddenNumber ? 'none' : 'actual'}"/>`);
  if (bar % 2 === 1 && index === 0) marks.push('<slur type="start" number="1" placement="above"/>');
  if (bar % 2 === 0 && index === 11) marks.push('<slur type="stop" number="1" placement="above"/>');
  const articulations = [];
  if (staff === 1 && index === 0 && bar % 4 === 1) articulations.push('<staccato/>');
  if (staff === 1 && index === 6) articulations.push('<tenuto/>');
  if (staff === 1 && index === 3 && [1, 9].includes(bar)) articulations.push('<accent/>');
  if (articulations.length) marks.push(`<articulations>${articulations.join('')}</articulations>`);
  const pitch = rest
    ? `<rest><display-step>${bar === 4 ? 'E' : 'F'}</display-step><display-octave>${bar === 4 ? 4 : 5}</display-octave></rest>`
    : pitchXML(midi);
  return `      <note>${pitch}<duration>4</duration><voice>${staff}</voice><type>eighth</type>`
    + '<time-modification><actual-notes>3</actual-notes><normal-notes>2</normal-notes><normal-type>eighth</normal-type></time-modification>'
    + `<stem>${staff === 1 ? 'up' : 'down'}</stem><staff>${staff}</staff>`
    + `<beam number="1">${['begin', 'continue', 'end'][index % 3]}</beam>`
    + `<notations>${marks.join('')}</notations></note>`;
}

export function originalMusicXML(licenseText) {
  const rights = licenseText.trim().replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
  const notes = originalNotes();
  const measures = [];
  for (let bar = 1; bar <= 16; bar += 1) {
    const lines = [`    <measure number="${bar}">`];
    if (bar === 1) {
      lines.push('      <attributes><divisions>12</divisions><key><fifths>0</fifths></key><time><beats>4</beats><beat-type>4</beat-type></time><staves>2</staves><clef number="1"><sign>G</sign><line>2</line></clef><clef number="2"><sign>G</sign><line>2</line></clef></attributes>');
      lines.push('      <direction><direction-type><metronome><beat-unit>quarter</beat-unit><per-minute>120</per-minute></metronome></direction-type><sound tempo="120"/></direction>');
    }
    if ([5, 9, 13].includes(bar)) {
      const treble = bar === 9;
      lines.push(`      <attributes><clef number="2"><sign>${treble ? 'G' : 'F'}</sign><line>${treble ? 2 : 4}</line></clef></attributes>`);
    }
    if (bar % 4 === 1) lines.push('      <direction placement="above"><direction-type><words>lightly</words></direction-type><staff>1</staff></direction>');
    if ([1, 9].includes(bar)) lines.push(`      <direction placement="below"><direction-type><dynamics><${bar === 1 ? 'mp' : 'mf'}/></dynamics></direction-type><staff>1</staff></direction>`);
    const wedge = {1: 'crescendo', 4: 'stop', 9: 'diminuendo', 12: 'stop'}[bar];
    if (wedge) lines.push(`      <direction placement="below"><direction-type><wedge type="${wedge}" number="1"/></direction-type><staff>1</staff></direction>`);
    lines.push(`      <direction placement="below"><direction-type><pedal type="${bar % 2 ? 'start' : 'stop'}" line="yes"/></direction-type><staff>2</staff></direction>`);
    for (const staff of [1, 2]) {
      if (staff === 2) lines.push('      <backup><duration>48</duration></backup>');
      lines.push(...notes.filter((note) => note.bar === bar && note.staff === staff).map(noteXML));
    }
    if (bar % 4 === 0) lines.push(`      <barline location="right"><bar-style>${bar === 16 ? 'light-heavy' : 'light-light'}</bar-style></barline>`);
    lines.push('    </measure>');
    measures.push(lines.join('\n'));
  }
  return '<?xml version="1.0" encoding="UTF-8"?>\n'
    + '<!-- Original music generated by scripts/demo-assets.mjs; provenance: apps/doc/webmusic/assets.json in the source repository. -->\n'
    + '<score-partwise version="3.1">\n'
    + `  <work><work-title>${title}</work-title></work>\n`
    + `  <identification><creator type="composer">${author}</creator><rights>${rights}</rights><source>https://github.com/koperative-lab/WebMusic/blob/main/scripts/demo-assets.mjs</source></identification>\n`
    + '  <part-list><score-part id="P1"><part-name>Piano</part-name><score-instrument id="I1"><instrument-name>Piano</instrument-name></score-instrument><midi-instrument id="I1"><midi-channel>1</midi-channel><midi-program>1</midi-program></midi-instrument></score-part></part-list>\n'
    + `  <part id="P1">\n${measures.join('\n')}\n  </part>\n</score-partwise>\n`;
}

function u16(value) { const data = Buffer.alloc(2); data.writeUInt16LE(value); return data; }
function u32(value) { const data = Buffer.alloc(4); data.writeUInt32LE(value >>> 0); return data; }
function crc32(data) {
  let crc = 0xffffffff;
  for (const byte of data) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit += 1) crc = (crc >>> 1) ^ ((crc & 1) ? 0xedb88320 : 0);
  }
  return (crc ^ 0xffffffff) >>> 0;
}

// A small deterministic ZIP writer using the standard uncompressed method.
// Fixed DOS timestamps avoid byte changes on subsequent generation.
function zipStored(entries) {
  const local = [];
  const central = [];
  let offset = 0;
  for (const [filename, content] of entries) {
    const name = Buffer.from(filename);
    const data = Buffer.from(content);
    const crc = u32(crc32(data));
    const common = Buffer.concat([u16(0), u16(0), u16(0), u16(33), crc, u32(data.length), u32(data.length), u16(name.length), u16(0)]);
    const header = Buffer.concat([u32(0x04034b50), u16(20), common, name]);
    local.push(header, data);
    central.push(Buffer.concat([u32(0x02014b50), u16(20), u16(20), common, u16(0), u16(0), u16(0), u32(0), u32(offset), name]));
    offset += header.length + data.length;
  }
  const directory = Buffer.concat(central);
  return Buffer.concat([...local, directory, u32(0x06054b50), u16(0), u16(0), u16(entries.length), u16(entries.length), u32(directory.length), u32(offset), u16(0)]);
}

export function originalMXL(xml) {
  return zipStored([
    ['mimetype', 'application/vnd.recordare.musicxml'],
    ['META-INF/container.xml', '<?xml version="1.0"?><container><rootfiles><rootfile full-path="score.xml" media-type="application/vnd.recordare.musicxml+xml"/></rootfiles></container>'],
    ['score.xml', xml],
  ]);
}

function variableLength(value) {
  const bytes = [value & 127];
  while ((value >>= 7) > 0) bytes.unshift((value & 127) | 128);
  return bytes;
}

export function originalMIDI(licenseText) {
  const meta = (type, text) => { const data = Buffer.from(text); return [0, 255, type, ...variableLength(data.length), ...data]; };
  // Format 1, one musical track per hand. Each track contains its own notes;
  // there is no empty conductor part for Rack demos to accidentally adopt.
  const tracks = [1, 2].map((staff) => {
    const channel = staff - 1;
    const bytes = [...meta(3, staff === 1 ? 'Upper' : 'Lower'), ...meta(2, licenseText.trim()),
      ...meta(1, `${title} — ${author}`), 0, 255, 81, 3, 7, 161, 32, 0, 255, 88, 4, 4, 2, 24, 8, 0, 192 + channel, 0];
    const events = originalNotes().filter((note) => !note.rest && note.staff === staff).flatMap((note) => {
      const tick = (note.bar - 1) * 1920 + note.index * 160;
      return [{tick, on: true, midi: note.midi}, {tick: tick + 160, on: false, midi: note.midi}];
    }).sort((a, b) => a.tick - b.tick || Number(a.on) - Number(b.on) || a.midi - b.midi);
    let previous = 0;
    for (const event of events) {
      bytes.push(...variableLength(event.tick - previous), (event.on ? 144 : 128) + channel, event.midi, event.on ? 80 : 0);
      previous = event.tick;
    }
    bytes.push(0, 255, 47, 0);
    const track = Buffer.from(bytes);
    const size = Buffer.alloc(4); size.writeUInt32BE(track.length);
    return Buffer.concat([Buffer.from('MTrk'), size, track]);
  });
  return Buffer.concat([Buffer.from('MThd'), Buffer.from([0, 0, 0, 6, 0, 1, 0, 2, 1, 224]), ...tracks]);
}

function riffChunk(id, data) {
  return Buffer.concat([Buffer.from(id), u32(data.length), data, ...(data.length % 2 ? [Buffer.alloc(1)] : [])]);
}

/** Stereo additive synthesis of the same pitched events, without external samples. */
export function originalWAV(licenseText) {
  const frames = sampleRate * durationSeconds;
  const mixed = new Int32Array(frames * 2);
  const noteFrames = sampleRate / 6; // Each triplet eighth lasts 1/6 second at 120 BPM.
  const attackFrames = 220;
  const releaseFrames = 1543;
  const triangle = (phase) => 32767 - Math.floor(Math.abs(phase - 0x80000000) / 32768);
  for (const note of originalNotes().filter((entry) => !entry.rest)) {
    const start = ((note.bar - 1) * 12 + note.index) * noteFrames;
    const step = Math.round(0x100000000 * 440 * 2 ** ((note.midi - 69) / 12) / sampleRate);
    let phase = 0x40000000;
    for (let frame = 0; frame < noteFrames; frame += 1) {
      const envelope = Math.min(1, frame / attackFrames, (noteFrames - 1 - frame) / releaseFrames);
      const tone = triangle(phase) * 0.8 + triangle((phase * 2) >>> 0) * 0.2;
      const value = Math.round(tone * envelope * 0.22);
      const offset = (start + frame) * 2;
      mixed[offset] += Math.round(value * (note.staff === 1 ? 0.7 : 1));
      mixed[offset + 1] += Math.round(value * (note.staff === 1 ? 1 : 0.7));
      phase = (phase + step) >>> 0;
    }
  }
  const pcm = Buffer.alloc(frames * 4);
  for (let index = 0; index < mixed.length; index += 1) {
    if (Math.abs(mixed[index]) > 32767) throw new Error('Original demo synthesis clipped.');
    pcm.writeInt16LE(mixed[index], index * 2);
  }
  const format = Buffer.concat([u16(1), u16(2), u32(sampleRate), u32(sampleRate * 4), u16(4), u16(16)]);
  const text = (value) => Buffer.from(`${value}\0`);
  const info = Buffer.concat([Buffer.from('INFO'),
    riffChunk('INAM', text(title)), riffChunk('IART', text(author)),
    riffChunk('ICOP', text(licenseText.trim())), riffChunk('ISFT', text('WebMusic scripts/demo-assets.mjs'))]);
  const chunks = Buffer.concat([riffChunk('fmt ', format), riffChunk('LIST', info), riffChunk('data', pcm)]);
  return Buffer.concat([Buffer.from('RIFF'), u32(chunks.length + 4), Buffer.from('WAVE'), chunks]);
}

const digest = (bytes) => createHash('sha256').update(bytes).digest('hex');
const hasLicenseMetadata = (bytes, license) => bytes.subarray(0, 3).toString() === 'ID3'
  && bytes.includes(Buffer.from(license.trim()));
const isReviewedMp3 = (bytes, license) => digest(bytes) === encodedAudioHash && hasLicenseMetadata(bytes, license);

async function readOptional(filename) {
  try {
    return await readFile(filename);
  } catch (error) {
    if (error?.code === 'ENOENT') return undefined;
    throw error;
  }
}
const encodeArguments = (wav, mp3, license) => ['-hide_banner', '-loglevel', 'error', '-y',
  '-fflags', '+bitexact', '-i', wav, '-map_metadata', '-1', '-c:a', 'libmp3lame', '-b:a', '128k',
  '-flags:a', '+bitexact', '-id3v2_version', '3', '-write_id3v1', '0',
  '-metadata', `title=${title}`, '-metadata', `artist=${author}`, '-metadata', `copyright=${license.trim()}`, mp3];

export async function processDemoAssets({check = false, repositoryDirectory = root} = {}) {
  const publicDirectory = path.join(repositoryDirectory, 'apps/doc/webmusic/public');
  const manifestFile = path.join(repositoryDirectory, 'apps/doc/webmusic/assets.json');
  const projectLicense = await readFile(path.join(repositoryDirectory, 'LICENSE'), 'utf8');
  if (!projectLicense.trim()) throw new Error('Empty project license.');
  const mxl = `mxl/${basename}.mxl`;
  const midi = `midi/${basename}.mid`;
  const wav = `wav/${basename}.wav`;
  const mp3 = `mp3/${basename}.mp3`;
  const generated = new Map([
    [mxl, originalMXL(originalMusicXML(projectLicense))],
    [midi, originalMIDI(projectLicense)],
    [wav, originalWAV(projectLicense)],
    [licensePath, Buffer.from(projectLicense)],
  ]);
  const allowedFiles = new Set([...generated.keys(), mp3, 'favicon.svg', inventoryPath]);
  const walk = async (directory) => {
    for (const entry of await readdir(directory, {withFileTypes: true})) {
      const filename = path.join(directory, entry.name);
      if (entry.isDirectory()) await walk(filename);
      else if (!entry.isFile() || !allowedFiles.has(path.relative(publicDirectory, filename).split(path.sep).join('/'))) {
        throw new Error(`Public file has no reviewed provenance: ${filename}`);
      }
    }
  };
  await walk(publicDirectory);
  // --write regenerates only the authored media; it never approves arbitrary icons.
  if (digest(await readFile(path.join(publicDirectory, 'favicon.svg'))) !== iconHash) {
    throw new Error('The original icon changed; review its provenance before replacing the trusted hash.');
  }
  const mp3File = path.join(publicDirectory, mp3);
  // The reviewed MP3 stays valid only for the WAV it was encoded from. Compare
  // with that pin, not the WAV on disk, which an earlier failed write may
  // already have regenerated.
  const wavHash = digest(generated.get(wav));
  const sourceReviewed = wavHash === encodedSourceHash;
  // Only an authoring write can keep or replace the MP3; a check reads it once below.
  const reviewedMp3 = check ? undefined : await readOptional(mp3File);
  for (const [relative, expected] of generated) {
    const filename = path.join(publicDirectory, relative);
    if (check) {
      if (!expected.equals(await readFile(filename))) throw new Error(`Stale original demo: ${relative}`);
    } else {
      await mkdir(path.dirname(filename), {recursive: true});
      await writeFile(filename, expected);
    }
  }
  if (!check && !(sourceReviewed && reviewedMp3 && isReviewedMp3(reviewedMp3, projectLicense))) {
    // This optional authoring tool is not required for --check or normal CI builds.
    // Encode outside the public tree and install only the reviewed bytes, so a
    // different encoder build can never replace the trusted file.
    const scratch = await mkdtemp(path.join(os.tmpdir(), 'webmusic-demo-mp3-'));
    try {
      const candidate = path.join(scratch, `${basename}.mp3`);
      try {
        execFileSync('ffmpeg', encodeArguments(path.join(publicDirectory, wav), candidate, projectLicense));
      } catch (error) {
        // Name the reason a new MP3 is needed, not only the encoder failure.
        const reason = sourceReviewed
          ? 'The reviewed MP3 is missing or changed'
          : `The generated WAV changed (sha256 ${wavHash}) and its MP3 must be re-encoded and reviewed`;
        throw new Error(`${reason}; encoding requires ffmpeg with libmp3lame (${error instanceof Error ? error.message : String(error)}).`, {cause: error});
      }
      const encoded = await readFile(candidate);
      if (!sourceReviewed || !isReviewedMp3(encoded, projectLicense)) {
        throw new Error(`The encoded original MP3 changed (WAV sha256 ${wavHash}, MP3 sha256 ${digest(encoded)}); review its source, encoder and decoded audio before replacing both trusted hashes.`);
      }
      await mkdir(path.dirname(mp3File), {recursive: true});
      await writeFile(mp3File, encoded);
    } finally {
      await rm(scratch, {recursive: true, force: true});
    }
  }
  if (!sourceReviewed) {
    throw new Error(`The reviewed MP3 was encoded from a different WAV (generated sha256 ${wavHash}); regenerate and review the MP3 before replacing both trusted hashes.`);
  }
  const mp3Bytes = await readFile(mp3File);
  if (digest(mp3Bytes) !== encodedAudioHash) {
    throw new Error('The encoded original MP3 changed; review its source, encoder and decoded audio before replacing the trusted hash.');
  }
  if (!hasLicenseMetadata(mp3Bytes, projectLicense)) {
    throw new Error('The MP3 must retain its complete MIT copyright metadata.');
  }
  const asset = async (filename, assetTitle, source) => ({path: filename, title: assetTitle,
    author, source, license: 'MIT', sourceLicenseFile: 'LICENSE', distributedLicenseFile: licensePath,
    sha256: digest(await readFile(path.join(publicDirectory, filename)))});
  const source = 'scripts/demo-assets.mjs';
  const provenance = {schemaVersion: 3, title, author,
    generator: {path: source, sha256: digest(await readFile(fileURLToPath(import.meta.url)))},
    originalStudyCommit: 'b714a004a0f604ad6717704d237cee3409ad14d1',
    musicalTiming: {measures: 16, beatsPerMeasure: 4, quarterNotesPerMinute: 120, durationSeconds},
    assets: await Promise.all([
      asset(midi, `${title} (MIDI; Upper and Lower parts)`, source),
      asset(mxl, `${title} (MusicXML; piano with two staves)`, source),
      asset(wav, `${title} (synthesized stereo PCM)`, source),
      asset(mp3, `${title} (MP3)`, `${source}; libmp3lame encoding of ${wav}, 128 kbps stereo, ID3v2.3`),
      asset('favicon.svg', 'WebMusic note icon', 'Original SVG paths retained from repository commit b714a004a0f604ad6717704d237cee3409ad14d1'),
      asset(licensePath, 'WebMusic demo asset MIT license', 'LICENSE'),
    ])};
  const serialized = JSON.stringify(provenance, null, 2) + '\n';
  for (const filename of [manifestFile, path.join(publicDirectory, inventoryPath)]) {
    if (check) {
      if (await readFile(filename, 'utf8') !== serialized) throw new Error(`Asset provenance inventory mismatch: ${filename}`);
    } else await writeFile(filename, serialized);
  }
  return {generated: generated.size, assets: provenance.assets.length, publicFiles: allowedFiles.size};
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const args = process.argv.slice(2);
  if (args.some((arg) => !['--check', '--write'].includes(arg)) || (args.includes('--check') && args.includes('--write'))) {
    throw new Error('Usage: node scripts/demo-assets.mjs [--check|--write]');
  }
  const check = !args.includes('--write');
  const result = await processDemoAssets({check});
  console.log(`Demo assets ${check ? 'verified' : 'written'}: ${result.generated} generated files, ${result.assets} provenance records, ${result.publicFiles} public files.`);
}
